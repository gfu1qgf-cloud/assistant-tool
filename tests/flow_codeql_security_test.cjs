const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.join(__dirname,'../browser_extensions/flow_bridge');
const ui=fs.readFileSync(path.join(root,'injects/ui.js'),'utf8');
const isolated=fs.readFileSync(path.join(root,'content-isolated.js'),'utf8');
const guard=ui.split('\n').find(line=>line.includes('if (!(host === "labs.google"'));
assert(guard,'the account bridge must use explicit host boundaries');
const expression=guard.trim().slice('if (!('.length,-')) return;'.length);
const accepts=vm.runInNewContext('(host,isVidsPage=()=>false)=>('+expression+')');
for(const host of ['labs.google','flow.google.com','x.labs.google','x.flow.google.com'])assert(accepts(host),host);
for(const host of ['evilflow.google.com','notlabs.google','flow.google.com.evil.test','labs.google.evil.test','127.0.0.1'])assert(!accepts(host),host);
const calls=[];
const bootLog=isolated.split('\n').find(line=>line.includes('消息桥梁脚本已成功注入当前页面！URL='));
const address='https://flow.google.com/project/a?%cforged\nline';
vm.runInNewContext(bootLog,{console:{log:(...args)=>calls.push(args)},location:{href:address}});
assert(calls[0][0].endsWith('URL=%s'));
assert(!calls[0][0].includes(address));
assert.equal(calls[0][2],address,'untrusted URL is data, not a console format string');
const logger=ui.split('\n').find(line=>line.includes('const log = (...a) => console.log("[FlowAccount]'));
const ctx={console:{log:(...args)=>calls.push(args)}};vm.createContext(ctx);
vm.runInContext(logger+'\nglobalThis.probe=log;',ctx);
ctx.probe('first\n[FAKE]\rnext\u2028more\u2029last');
assert.equal(calls.at(-1)[0],'[FlowAccount] %s');
assert(!/[\r\n\u2028\u2029]/.test(calls.at(-1)[1]));
assert(!ui.includes('console.log(`[FlowUI] 正在关联素材:'));
assert(!ui.includes('console.log(`[FlowUI] 开始同步视频设置:'));
console.log('Flow CodeQL follow-up: host boundaries, literal format strings and single-line diagnostics passed.');
